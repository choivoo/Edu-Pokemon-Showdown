export const glyph = (ch: string) => G[ch] ?? G[' ']
export const textWidth = (s: string, scale: number, gap = 1) => [...s].reduce((w, ch) => w + (glyph(ch)[0].length + gap) * scale, 0) - gap * scale

/** 글자를 점(스케일 배)으로 찍는다. draw(x, y, w, h) 로 사각형을 칠한다. */
export function eachDot(s: string, x: number, y: number, scale: number, put: (x: number, y: number, w: number, h: number) => void, gap = 1) {
  let cx = x
  for (const ch of s) {
    const g = glyph(ch)
    g.forEach((row, j) => [...row].forEach((c, i) => { if (c === '#') put(cx + i * scale, y + j * scale, scale, scale) }))
    cx += (g[0].length + gap) * scale
  }
}
