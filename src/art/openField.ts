/** Large continuous, camera-scrolling 2.5D tile world.
 * Built entirely from Canvas paths: no 3D engine and no lifted game art.
 * Diamonds, extruded cliffs, contact shadows and depth sorting create an
 * oblique diorama view in which sprites remain crisp PokéAPI 2D pixels.
 */
import type { Theme } from '../lib/stages'
export const WORLD_BOUNDS={left:0,right:3220,top:0,bottom:1460} as const
const palette:Record<Theme,{ground:string;light:string;dark:string;edge:string;water:string;rock:string;tree:string;foliage:string;path:string}>={
 forest:{ground:'#92db78',light:'#b4ed88',dark:'#72bd69',edge:'#79533e',water:'#2daee9',rock:'#a9bdb8',tree:'#6a563e',foliage:'#4cad65',path:'#f7cf7f'},
 beach:{ground:'#e9d29a',light:'#f8e5af',dark:'#b8af7a',edge:'#9d7958',water:'#20a5e3',rock:'#adae9f',tree:'#927d53',foliage:'#7dbd6b',path:'#ffdfa8'},
 cave:{ground:'#a4a5b8',light:'#c7c5db',dark:'#7b799b',edge:'#51486a',water:'#318fd0',rock:'#797b9f',tree:'#5d4e7d',foliage:'#aa9abc',path:'#c0b8b1'},
 gorge:{ground:'#d8c37f',light:'#eadba9',dark:'#ac975b',edge:'#86694b',water:'#48afe0',rock:'#a48f73',tree:'#87643a',foliage:'#8fba62',path:'#f5dfa4'},
 volcano:{ground:'#917875',light:'#b8a19a',dark:'#675159',edge:'#47323c',water:'#e9693b',rock:'#837181',tree:'#634d4b',foliage:'#c0805f',path:'#d0a28b'},
 altar:{ground:'#b4abd0',light:'#ddd4f0',dark:'#9185b5',edge:'#615985',water:'#69b8ef',rock:'#d7c3e6',tree:'#8277ae',foliage:'#e0b7ed',path:'#ebdfeb'},
}
const hash=(a:number,b:number,n=0)=>{let x=Math.imul(a+6125,374761393)^Math.imul(b-1993,668265263)^Math.imul(n+5,1274126177);x=Math.imul(x^(x>>>13),1274126177);return ((x^(x>>>16))>>>0)/4294967296}
const diamond=(ctx:CanvasRenderingContext2D,x:number,y:number,rx:number,ry:number)=>{
 ctx.beginPath();ctx.moveTo(x,y-ry);ctx.lineTo(x+rx,y);ctx.lineTo(x,y+ry);ctx.lineTo(x-rx,y);ctx.closePath()
}
function cube(ctx:CanvasRenderingContext2D,x:number,y:number,s:number,h:number,p:{rock:string;dark:string;light:string},t=0){
 const top=y-h
 ctx.fillStyle='rgba(27,43,34,.22)';ctx.beginPath();ctx.ellipse(x,y+4,s*.8,s*.28,0,0,Math.PI*2);ctx.fill()
 ctx.fillStyle=p.dark;ctx.beginPath();ctx.moveTo(x-s,top);ctx.lineTo(x,top+s*.26);ctx.lineTo(x,y+s*.25);ctx.lineTo(x-s,y);ctx.closePath();ctx.fill()
 ctx.fillStyle=p.rock;ctx.beginPath();ctx.moveTo(x+s,top);ctx.lineTo(x,top+s*.26);ctx.lineTo(x,y+s*.25);ctx.lineTo(x+s,y);ctx.closePath();ctx.fill()
 ctx.fillStyle=p.light;diamond(ctx,x,top,s,s*.26);ctx.fill()
 if(t){ctx.fillStyle='#fff5';ctx.fillRect(x-s*.6,top-s*.08,s*.22,3)}
}
function tree(ctx:CanvasRenderingContext2D,x:number,y:number,sz:number,p:typeof palette[Theme],seed:number){
 cube(ctx,x,y,sz*.28,sz*.5,{rock:p.tree,dark:'#634635',light:'#b79053'})
 cube(ctx,x,y-sz*.28,sz*.72,sz*.72,{rock:p.tree,dark:p.foliage,light:p.light},seed)
 cube(ctx,x,y-sz*.73,sz*.92,sz*.9,{rock:p.foliage,dark:p.tree,light:p.light},seed)
}
export function drawOpenField(ctx:CanvasRenderingContext2D,theme:Theme,cameraX:number,cameraY:number,t:number){
 const p=palette[theme],left=cameraX-560,right=cameraX+560,top=cameraY-350,bottom=cameraY+350
 ctx.fillStyle=p.water;ctx.fillRect(left-150,top-150,right-left+300,bottom-top+300)
 const tileX=72,tileY=36
 const decos:Array<{x:number;y:number;type:number;sz:number;seed:number}>=[]
 // Generated by an isometric screen-plane projection: x=(i-j)*72,
 // y=(i+j)*36. The resulting diamonds tile perfectly without gaps.
 for(let i=0;i<51;i++)for(let j=0;j<51;j++){
   const x=(i-j)*tileX+1620,y=(i+j)*tileY-800
   if(x<left-110||x>right+110||y<top-90||y>bottom+90)continue
   const f=hash(i,j,7),water=f<.05&&(i+j)%5!==0
   const coast=x<95||x>WORLD_BOUNDS.right-80||y<85||y>WORLD_BOUNDS.bottom-90
   const color=water||coast?p.water:f<.38?p.light:f>.86?p.dark:p.ground
   diamond(ctx,x,y,tileX,tileY)
   ctx.fillStyle=color;ctx.fill()
   ctx.strokeStyle=water?'#65dcfa55':p.dark+'29';ctx.lineWidth=1;ctx.stroke()
   if(water||coast){
     if(hash(i,j,3)>.55){ctx.fillStyle='#ffffff3b';ctx.fillRect(x-16,y-2,23,3)}
     continue
   }
   const q=hash(i,j,18), d=Math.abs((x-450)-Math.sin((x/430))*170-620)
   const path=d<125||Math.abs(y-650-Math.sin(x/350)*115)<110
   if(path&&q<.19){diamond(ctx,x,y,25,12);ctx.fillStyle=p.path+'77';ctx.fill()}
   if(q>.965&&!path)decos.push({x,y:y+10,type:2,sz:35+hash(i,j,4)*19,seed:j})
   else if(q>.87&&!path)decos.push({x,y:y+12,type:1,sz:30+hash(i,j,4)*25,seed:i})
   else if(q<.125){
     ctx.fillStyle=q<.04?'#fffada':'#fce7ae';const fx=x+hash(i,j,22)*16-8,fy=y+hash(i,j,23)*12-5
     ctx.fillRect(fx,fy,3,3);ctx.fillRect(fx-4,fy+2,2,2);ctx.fillRect(fx+5,fy+2,2,2)
   }
 }
 decos.sort((a,b)=>a.y-b.y)
 for(const d of decos){
   if(d.type===1)tree(ctx,d.x,d.y,d.sz,p,d.seed)
   else cube(ctx,d.x,d.y,d.sz*.6,d.sz*.72,{rock:p.rock,dark:p.dark,light:p.light},1)
 }
 if(theme==='volcano'||theme==='altar'){
   ctx.globalAlpha=.5+.13*Math.sin(t*2)
   for(let i=0;i<10;i++){
    const x=left+((hash(i,4,8)*1150+t*13)%1150),y=top+hash(i,5,7)*740
    ctx.fillStyle=theme==='volcano'?'#ffbf6c':'#fff3c8';ctx.fillRect(x,y,4,4)
   }
   ctx.globalAlpha=1
 }
}
