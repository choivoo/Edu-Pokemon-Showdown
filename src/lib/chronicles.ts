export const CHRONICLES: Chronicle[] = ACTS.flatMap((act, area) =>
  act.map((script, index) => ({
    id: stageId(area, index), area, index,
    title: script.title, lines: script.lines,
  })),
)

export function chronicleFor(area: number, index: number): Chronicle | null {
  return CHRONICLES.find(c => c.area === area && c.index === index) ?? null
}

export function chronicleUnlocked(cleared: Record<string, true>, chronicle: Chronicle): boolean {
  return !!cleared[chronicle.id]
}

export function chronicleCount(cleared: Record<string, true>): number {
  return CHRONICLES.filter(c => chronicleUnlocked(cleared, c)).length
}
